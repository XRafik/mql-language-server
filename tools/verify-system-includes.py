#!/usr/bin/env python3
"""Opt-in Tier-1 evidence script for system-include resolution (issue #179, S6).

A maintainer runs this against a REAL MetaTrader `MQL5/Include` tree:

    ./tools/verify-system-includes.sh /path/to/MetaTrader5/MQL5/Include

The script builds (or reuses) the language server, drives a real LSP session
over stdio with `initializationOptions.systemIncludeRoots = [<given path>]`,
opens a temporary `.mq5` document that pulls two system headers and uses three
Standard-Library types declared behind them — `CTrade` (declared directly in
`Trade.mqh`), `CPositionInfo` (declared in `Trade/PositionInfo.mqh`, reached
through the quoted same-directory hop inside it) and `CArrayLong` (declared in
`Arrays/ArrayLong.mqh`, pulled by its own angle entry) — waits for the server's
diagnostics, and asserts that NO undeclared-symbol diagnostics (code 5070 for
MQL5) are produced for those declarations. The three types cover the three
include forms the real library uses: direct declaration, quoted same-directory
hop, and angle entry into a subdirectory. A JSON evidence object is printed to
stdout (progress and verdict lines go to stderr, so redirecting stdout yields a file that
parses as JSON).

Exit codes:
    0  assertion holds: zero code-5070 diagnostics (Tier 1 works)
    1  assertion failed: undeclared-symbol diagnostics were observed
    2  usage / precondition error (missing argument, not a directory, or the
       tree does not contain `Trade/Trade.mqh` up to case differences)
    3  the server could not be built or the LSP session failed

Dependencies: `dotnet` and the Python 3 standard library only. The include
root is ALWAYS a command-line argument; no default MetaTrader path is ever
assumed. This script is not referenced by any workflow and never runs in CI.
"""

import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
import threading
import time
from pathlib import Path

# --- Tunables ---------------------------------------------------------------

BUILD_TIMEOUT_SECONDS = 900
VERSION_TIMEOUT_SECONDS = 60
INITIALIZE_TIMEOUT_SECONDS = 60
FIRST_DIAGNOSTICS_TIMEOUT_SECONDS = 180
DIAGNOSTICS_SETTLE_SECONDS = 2.0
PULL_TIMEOUT_SECONDS = 60
SHUTDOWN_TIMEOUT_SECONDS = 30

UNDECLARED_SYMBOL_CODE_MQL5 = "5070"  # Mql5DiagnosticBase (5000) + 70, string on the wire

# Two angle entries, not one: the real `Trade/Trade.mqh` does NOT reach the
# collection headers (it pulls <Object.mqh> plus the quoted siblings
# OrderInfo/HistoryOrderInfo/PositionInfo/DealInfo), so asserting CArrayLong
# through it would fail against a real installation for the wrong reason.
INCLUDE_ENTRIES = ("Trade\\Trade.mqh", "Arrays\\ArrayLong.mqh")

PROBE_DOCUMENT_NAME = "verify_system_include_probe.mq5"
# Three uses covering the three include forms the real Standard Library
# exercises: CTrade (declared in the first header), CPositionInfo (declared in
# a quoted same-directory sibling that header pulls) and CArrayLong (declared
# behind the second angle entry). Kept free of content that triggers unrelated
# heuristics (no "Unkown*" tokens, non-empty OnInit body).
PROBE_DOCUMENT_TEXT = (
    "// Tier-1 evidence probe generated by tools/verify-system-includes.py (issue #179).\n"
    '#property copyright "verify-system-includes"\n'
    "#include <Trade\\Trade.mqh>\n"
    "#include <Arrays\\ArrayLong.mqh>\n"
    "\n"
    "CTrade        g_trade;\n"
    "CPositionInfo g_position;\n"
    "CArrayLong    g_values;\n"
    "\n"
    "int OnInit()\n"
    "{\n"
    "   return(INIT_SUCCEEDED);\n"
    "}\n"
    "\n"
    "void OnDeinit(const int reason)\n"
    "{\n"
    "}\n"
    "\n"
    "void OnTick()\n"
    "{\n"
    "   g_values.Add(1);\n"
    "}\n"
)


def fail(message, exit_code):
    """Print an actionable failure to stderr and exit with a non-zero code."""
    print(f"❌ Error: {message}", file=sys.stderr)
    sys.exit(exit_code)


# --- Precondition checks ----------------------------------------------------


def find_case_insensitive(root, *parts):
    """Walk `parts` under `root` matching each component case-insensitively.

    Returns the resolved path when every component exists (final component
    must be a file), otherwise None.
    """
    current = root
    for part in parts:
        try:
            entries = os.listdir(current)
        except OSError:
            return None
        match = next((e for e in entries if e.lower() == part.lower()), None)
        if match is None:
            return None
        current = os.path.join(current, match)
    return current if os.path.isfile(current) else None


def validate_include_root(argv):
    if len(argv) != 1:
        fail(
            "missing required argument.\n"
            "Usage: ./tools/verify-system-includes.sh <path-to-MQL5/Include>\n"
            "The path must point at the Include directory of a real MetaTrader 5\n"
            "installation (the folder that contains Trade/Trade.mqh). It is never\n"
            "guessed and there is no default.",
            2,
        )

    root = Path(argv[0]).expanduser()
    if not root.is_dir():
        fail(f"'{argv[0]}' is not a directory. Pass the MQL5/Include directory of a MetaTrader 5 installation.", 2)

    root = root.resolve()
    trade_header = find_case_insensitive(str(root), "Trade", "Trade.mqh")
    if trade_header is None:
        try:
            top_level = ", ".join(sorted(os.listdir(root))[:20]) or "(empty directory)"
        except OSError:
            top_level = "(unreadable directory)"
        fail(
            f"'{root}' does not look like a MetaTrader MQL5/Include tree: expected a\n"
            f"'Trade{os.sep}Trade.mqh' header directly inside it (case-insensitive), but none was found.\n"
            f"Top-level entries: {top_level}.\n"
            "Pass the Include directory of a real installation, e.g.\n"
            "  <TerminalDataFolder>/MQL5/Include",
            2,
        )
    if find_case_insensitive(str(root), "Arrays", "ArrayLong.mqh") is None:
        fail(
            f"'{root}' is missing 'Arrays{os.sep}ArrayLong.mqh', which the probe needs to cover the\n"
            "subdirectory angle-entry form. Pass the MQL5/Include directory of a complete installation.",
            2,
        )
    return root, trade_header


# --- Server resolution (build or reuse) -------------------------------------


def resolve_server_command(repo_root):
    """Return (command_list, was_built). Honors MQL_LSP_SERVER to reuse a binary."""
    override = os.environ.get("MQL_LSP_SERVER")
    if override:
        # Resolve against the caller's cwd so the version probe and the server
        # process (which runs with cwd=repo_root) see the same binary.
        override_abs = os.path.abspath(override)
        if override_abs.endswith(".dll"):
            return ["dotnet", override_abs], False
        return shlex.split(override_abs), False

    project = repo_root / "src" / "MqlLanguageServer.Server.csproj"
    build = subprocess.run(
        ["dotnet", "build", "-c", "Release", str(project)],
        cwd=str(repo_root),
        capture_output=True,
        text=True,
        timeout=BUILD_TIMEOUT_SECONDS,
    )
    if build.returncode != 0:
        tail = "\n".join((build.stdout + "\n" + build.stderr).splitlines()[-25:])
        fail(f"the language server failed to build ({project}):\n{tail}", 3)

    dll = repo_root / "src" / "bin" / "Release" / "net10.0" / "mql-lsp-server.dll"
    if not dll.is_file():
        fail(f"expected the built server at '{dll}' but it is missing after a successful build.", 3)
    return ["dotnet", str(dll)], True


def capture_server_build(command, repo_root):
    """Run `--version` and extract (version, build_date) for the evidence object."""
    try:
        proc = subprocess.run(
            command + ["--version"],
            cwd=str(repo_root),
            capture_output=True,
            text=True,
            timeout=VERSION_TIMEOUT_SECONDS,
        )
        output = proc.stdout + proc.stderr
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"version": "unknown", "buildDate": "unknown", "error": str(exc)}
    version = re.search(r"MQL Language Server (\S+)", output)
    build_date = re.search(r"Build Date:\s*(\S+)", output)
    return {
        "version": version.group(1) if version else "unknown",
        "buildDate": build_date.group(1) if build_date else "unknown",
    }


# --- Minimal LSP client over stdio (JSON-RPC, Content-Length framing) -------


class LspSession:
    def __init__(self, command, cwd, on_stderr_tail):
        self.proc = subprocess.Popen(
            command,
            cwd=str(cwd),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        self._next_id = 1
        self._messages = []
        self._messages_lock = threading.Condition()
        self.stderr_tail = on_stderr_tail
        self._reader = threading.Thread(target=self._read_loop, daemon=True)
        self._reader.start()
        self._stderr = threading.Thread(target=self._stderr_loop, daemon=True)
        self._stderr.start()

    # -- transport

    def _send_raw(self, payload):
        body = json.dumps(payload).encode("utf-8")
        assert self.proc.stdin is not None
        self.proc.stdin.write(f"Content-Length: {len(body)}\r\n\r\n".encode("ascii") + body)
        self.proc.stdin.flush()

    def _read_loop(self):
        try:
            stdout = self.proc.stdout
            assert stdout is not None
            while True:
                headers = {}
                line = stdout.readline()
                if not line:
                    break
                while line not in (b"\r\n", b"\n", b""):
                    text = line.decode("ascii", errors="replace").strip()
                    if ":" in text:
                        key, _, value = text.partition(":")
                        headers[key.strip().lower()] = value.strip()
                    line = stdout.readline()
                length = int(headers.get("content-length", "0"))
                if length <= 0:
                    break
                body = stdout.read(length)
                if len(body) < length:
                    break
                with self._messages_lock:
                    self._messages.append(json.loads(body.decode("utf-8")))
                    self._messages_lock.notify_all()
        except Exception as exc:  # transport died; wake waiters with the error
            with self._messages_lock:
                self._messages.append({"__transport_error__": str(exc)})
                self._messages_lock.notify_all()
        finally:
            with self._messages_lock:
                self._messages.append({"__eof__": True})
                self._messages_lock.notify_all()

    def _stderr_loop(self):
        assert self.proc.stderr is not None
        for chunk in iter(lambda: self.proc.stderr.readline(), b""):
            self.stderr_tail(chunk.decode("utf-8", errors="replace").rstrip())

    # -- protocol helpers

    def notify(self, method, params):
        self._send_raw({"jsonrpc": "2.0", "method": method, "params": params})

    def request(self, method, params):
        request_id = self._next_id
        self._next_id += 1
        self._send_raw({"jsonrpc": "2.0", "id": request_id, "method": method, "params": params})
        return request_id

    def _auto_respond_to_server_requests(self, message):
        """Answer server→client requests so the server never blocks on us."""
        if message.get("method") and "id" in message and "result" not in message and "error" not in message:
            # Generic stand-in client: no configurations, no dynamic registrations.
            result = [] if message["method"] == "workspace/configuration" else None
            self._send_raw({"jsonrpc": "2.0", "id": message["id"], "result": result})

    def wait_for(self, predicate, timeout, action=None):
        """Consume messages until `predicate` matches or the deadline passes.

        Server→client requests are auto-answered; every consumed message is
        handed to `action` first. Returns the matching message or None.
        """
        deadline = time.monotonic() + timeout
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return None
            with self._messages_lock:
                while not self._messages:
                    if not self._messages_lock.wait(remaining):
                        return None  # deadline hit with nothing pending
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        return None
                message = self._messages.pop(0)
            if "__eof__" in message or "__transport_error__" in message:
                raise ConnectionError("server closed stdout or the transport failed")
            self._auto_respond_to_server_requests(message)
            if action is not None:
                action(message)
            if predicate(message):
                return message

    def close(self, force=False):
        try:
            if force:
                self.proc.kill()
            else:
                self.proc.wait(timeout=SHUTDOWN_TIMEOUT_SECONDS)
        except Exception:
            self.proc.kill()
            self.proc.wait(timeout=10)


# --- LSP session driver -----------------------------------------------------


def run_lsp_session(server_command, repo_root, include_root):
    """Drive initialize → didOpen → diagnostics → shutdown. Returns evidence dict."""
    evidence = {}
    stderr_lines = []

    def on_stderr_tail(line):
        stderr_lines.append(line)
        del stderr_lines[:-80]  # keep only the last 80 lines

    temp_dir = tempfile.mkdtemp(prefix="mql-lsp-verify-system-includes-")
    probe_path = Path(temp_dir) / PROBE_DOCUMENT_NAME
    probe_path.write_text(PROBE_DOCUMENT_TEXT, encoding="utf-8")
    probe_uri = probe_path.as_uri()
    root_uri = Path(temp_dir).as_uri()

    session = LspSession(server_command, repo_root, on_stderr_tail)
    published = {}

    def record_publishes(message):
        if message.get("method") == "textDocument/publishDiagnostics":
            published[message["params"]["uri"]] = message["params"].get("diagnostics", [])

    try:
        # initialize — the include root is delivered exactly as a client would.
        init_id = session.request(
            "initialize",
            {
                "processId": os.getpid(),
                "rootUri": root_uri,
                "workspaceFolders": [{"uri": root_uri, "name": PROBE_DOCUMENT_NAME}],
                "capabilities": {},
                "initializationOptions": {"systemIncludeRoots": [str(include_root)]},
            },
        )
        response = session.wait_for(
            lambda m: m.get("id") == init_id and ("result" in m or "error" in m),
            INITIALIZE_TIMEOUT_SECONDS,
            record_publishes,
        )
        if response is None:
            raise TimeoutError("server did not answer initialize")
        if "error" in response:
            raise RuntimeError(f"initialize failed: {response['error']}")
        evidence["serverCapabilitiesReceived"] = True

        session.notify("initialized", {})

        # didOpen — the probe uses CTrade and the transitively included CArrayLong.
        session.notify(
            "textDocument/didOpen",
            {
                "textDocument": {
                    "uri": probe_uri,
                    "languageId": "mq5",
                    "version": 1,
                    "text": PROBE_DOCUMENT_TEXT,
                }
            },
        )

        # Wait for the first push, then keep consuming until the stream settles.
        first = session.wait_for(
            lambda m: m.get("method") == "textDocument/publishDiagnostics"
            and m["params"]["uri"] == probe_uri,
            FIRST_DIAGNOSTICS_TIMEOUT_SECONDS,
            record_publishes,
        )
        if first is None:
            raise TimeoutError("server never published diagnostics for the probe document")
        session.wait_for(
            lambda m: False,  # pure settle wait: consume until the deadline
            DIAGNOSTICS_SETTLE_SECONDS,
            record_publishes,
        )

        # The pull channel shares the rule set with the push channel; query it
        # for the authoritative final state (the handler runs synchronously).
        diagnostics = None
        channel = "textDocument/publishDiagnostics"
        pull_id = session.request(
            "textDocument/diagnostic", {"textDocument": {"uri": probe_uri}}
        )
        pull = session.wait_for(
            lambda m: m.get("id") == pull_id and ("result" in m or "error" in m),
            PULL_TIMEOUT_SECONDS,
            record_publishes,
        )
        if pull is not None and "result" in pull and isinstance(pull["result"], dict):
            report = pull["result"]
            items = report.get("items")
            if items is None:
                items = (report.get("relatedFullDocumentDiagnosticReport") or {}).get("items", [])
            diagnostics = items
            channel = "textDocument/diagnostic"
        if diagnostics is None:
            diagnostics = published.get(probe_uri, [])

        evidence["diagnosticChannel"] = channel
        undeclared = [d for d in diagnostics if str(d.get("code")) == UNDECLARED_SYMBOL_CODE_MQL5]
        evidence["diagnostics"] = {
            "total": len(diagnostics),
            "undeclaredSymbol5070": len(undeclared),
            "undeclaredMessages": [d.get("message", "") for d in undeclared],
        }
        evidence["allDiagnostics"] = [
            {
                "code": str(d.get("code")),
                "severity": d.get("severity"),
                "message": d.get("message", ""),
                "range": d.get("range"),
            }
            for d in diagnostics
        ]
        evidence["closureResolved"] = len(undeclared) == 0
        evidence["assertion"] = "pass" if len(undeclared) == 0 else "fail"
    finally:
        # shutdown / exit — best effort; the evidence is already collected.
        try:
            shutdown_id = session.request("shutdown", None)
            session.wait_for(
                lambda m: m.get("id") == shutdown_id and ("result" in m or "error" in m),
                SHUTDOWN_TIMEOUT_SECONDS,
                record_publishes,
            )
            session.notify("exit", None)
            session.close()
        except Exception:
            session.close(force=True)

    return evidence


# --- Main -------------------------------------------------------------------


def main(argv):
    repo_root = Path(__file__).resolve().parent.parent
    if not (repo_root / "src" / "MqlLanguageServer.Server.csproj").is_file():
        fail("this script must live in <repo>/tools/ next to the project it verifies.", 2)

    include_root, trade_header = validate_include_root(argv)

    server_command, was_built = resolve_server_command(repo_root)
    build_info = capture_server_build(server_command, repo_root)

    print("🔎 Include root :", include_root, file=sys.stderr)
    print("🔎 Header found :", trade_header, file=sys.stderr)
    print("🚀 Server       :", " ".join(server_command), "(built)" if was_built else "(reused via MQL_LSP_SERVER)", file=sys.stderr)
    print("🚀 Server build :", build_info.get("version"), "/", build_info.get("buildDate"), file=sys.stderr)
    print("⏳ Driving LSP session...", file=sys.stderr, flush=True)

    try:
        evidence = run_lsp_session(server_command, repo_root, include_root)
    except (TimeoutError, ConnectionError, RuntimeError, OSError) as exc:
        fail(f"LSP session failed: {exc}", 3)

    evidence.update(
        {
            "script": "verify-system-includes",
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "includeRoot": str(include_root),
            "includeEntries": list(INCLUDE_ENTRIES),
            "server": {"command": server_command, **build_info},
        }
    )

    print(json.dumps(evidence, indent=2))

    if evidence["assertion"] != "pass":
        entries = ", ".join(f"<{entry}>" for entry in INCLUDE_ENTRIES)
        print(
            "❌ Tier-1 verification FAILED: undeclared-symbol (5070) diagnostics were\n"
            f"   produced for declarations reached through {entries}.\n"
            "   Observed: " + json.dumps(evidence["diagnostics"]["undeclaredMessages"], indent=2),
            file=sys.stderr,
        )
        sys.exit(1)

    print(
        "✅ Tier-1 verification passed: CTrade, CPositionInfo and CArrayLong resolved\n"
        f"   through {', '.join(f'<{entry}>' for entry in INCLUDE_ENTRIES)} with zero\n"
        "   undeclared-symbol diagnostics.",
        file=sys.stderr,
    )
    sys.exit(0)


if __name__ == "__main__":
    main(sys.argv[1:])
